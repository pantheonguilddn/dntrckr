import { jsonResponse, resolveRecordId } from '../../../../_utils/auth.js';
import { getCharacterStorageState } from '../../../../_utils/character-storage.js';

const MAIN_ID = 'pantheon-main';
const PAGE_LIMIT = 10000;
const finiteCursor = value => {
  const n = Number(value);
  return Number.isSafeInteger(n) && n >= 0 ? n : 0;
};

// Changes are keyed by a monotonic D1 storage revision, not a browser timestamp.
// The change index stores one latest revision per character/task key, preventing
// clock skew or rapid saves from causing a missed update between polls.
export async function onRequestGet(context) {
  const { params, request, env, data } = context;
  if (!data?.session?.discordId) return jsonResponse({ error:'Authentication required.' },401);
  const requestedId = String(params.id || '');
  const targetId = await resolveRecordId(env, requestedId);
  if (targetId !== MAIN_ID) return jsonResponse({ message:'Incremental progress is available only for the main Tracker.' },400);

  let state;
  try { state = await getCharacterStorageState(env); }
  catch (_) { return jsonResponse({ code:'CHARACTER_STORAGE_UNAVAILABLE', retryable:true, message:'Player storage is temporarily unavailable.' },503); }
  if (Number(state?.migration_complete) !== 1) {
    return jsonResponse({ code:'CHARACTER_STORAGE_NOT_READY', retryable:true, message:'Player storage is not ready for incremental synchronization.' },503);
  }

  const url = new URL(request.url);
  const sinceRevision = finiteCursor(url.searchParams.get('sinceRevision'));
  const highWater = Number(state?.revision) || 0;
  const cutoff = Date.now() - 42 * 24 * 60 * 60 * 1000;
  const clearedAt = Number(state?.analytics_history_cleared_at) || 0;
  if (sinceRevision > highWater) {
    return jsonResponse({ fullSnapshotRequired:true, metadata:{ characterStorageRevision:highWater } });
  }

  try {
    const feed = await env.PANTHEON_DB.prepare(`
      SELECT revision FROM tracker_storage_changes
      WHERE change_type = 'feed' AND character_key = '' AND task_key = '' AND week_key = '' LIMIT 1
    `).first();
    // A missing/stale feed marker means some revision was generated by an older
    // server version or a structural migration. Fall back once to a full snapshot.
    if (!feed || Number(feed.revision) !== highWater) {
      return jsonResponse({ fullSnapshotRequired:true, metadata:{ characterStorageRevision:highWater } });
    }
    const invalidation = await env.PANTHEON_DB.prepare(`
      SELECT revision FROM tracker_storage_changes
      WHERE change_type = 'full' AND revision > ? AND revision <= ? LIMIT 1
    `).bind(sinceRevision, highWater).first();
    if (invalidation) {
      return jsonResponse({ fullSnapshotRequired:true, metadata:{ characterStorageRevision:highWater } });
    }

    const [cellResult, timingResult] = await Promise.all([
      env.PANTHEON_DB.prepare(`
        SELECT o.character_name, c.task_key, c.task_name, c.state, c.note, c.updated_at, c.device_id,
               t.task_name AS definition_name
        FROM tracker_storage_changes ch
        JOIN character_task_cells c ON c.character_key = ch.character_key AND c.task_key = ch.task_key
        JOIN character_owners o ON o.character_key = c.character_key
        LEFT JOIN tracker_task_definitions t ON t.task_key = c.task_key
        WHERE ch.change_type = 'cell' AND ch.revision > ? AND ch.revision <= ?
        ORDER BY ch.revision ASC
        LIMIT ?
      `).bind(sinceRevision, highWater, PAGE_LIMIT + 1).all(),
      env.PANTHEON_DB.prepare(`
        SELECT o.character_name, t.week_key, t.task_key, t.task_name, t.state, t.at, t.owner_key,
               d.task_name AS definition_name
        FROM tracker_storage_changes ch
        JOIN character_completion_timing t ON t.character_key = ch.character_key AND t.task_key = ch.task_key AND t.week_key = ch.week_key
        JOIN character_owners o ON o.character_key = t.character_key
        LEFT JOIN tracker_task_definitions d ON d.task_key = t.task_key
        WHERE ch.change_type = 'timing' AND ch.revision > ? AND ch.revision <= ?
          AND t.at >= ? AND t.at >= ?
        ORDER BY ch.revision ASC
        LIMIT ?
      `).bind(sinceRevision, highWater, cutoff, clearedAt, PAGE_LIMIT + 1).all()
    ]);

    const cellRows = cellResult.results || [];
    const timingRows = timingResult.results || [];
    if (cellRows.length > PAGE_LIMIT || timingRows.length > PAGE_LIMIT) {
      return jsonResponse({ fullSnapshotRequired:true, metadata:{ characterStorageRevision:highWater } });
    }

    const cells = cellRows.map(row => ({
      characterName:String(row.character_name || '').trim(),
      taskName:String(row.task_name || row.definition_name || row.task_key || '').trim(),
      state:String(row.state || 'open'),
      note:String(row.note || ''),
      updatedAt:Number(row.updated_at) || 0,
      deviceId:String(row.device_id || '')
    })).filter(row => row.characterName && row.taskName);

    const timing = timingRows.map(row => ({
      characterName:String(row.character_name || '').trim(),
      weekKey:String(row.week_key || ''),
      taskName:String(row.task_name || row.definition_name || row.task_key || '').trim(),
      state:row.state === 'done' ? 'done' : 'open',
      at:Number(row.at) || 0,
      ownerKey:String(row.owner_key || '')
    })).filter(row => row.characterName && row.weekKey && row.taskName && row.at >= cutoff && row.at >= clearedAt);

    return jsonResponse({
      metadata:{ characterStorageRevision:highWater, characterStorageUpdatedAt:Number(state?.updated_at) || 0, sinceRevision },
      cells,
      timing
    });
  } catch (error) {
    return jsonResponse({ code:'CHARACTER_DELTA_READ_FAILED', retryable:true, message:`Incremental progress could not be read: ${String(error?.message || error).slice(0,220)}` },503);
  }
}
